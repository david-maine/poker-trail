const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { randomUUID } = require('node:crypto');
const { PGlite } = require('@electric-sql/pglite');
const { loader } = require('./support.cjs');

test('registration pause service scopes changes to an active event owned by the organiser', async () => {
  let session = { user: { id: 'owner' } }, failure = null;
  const calls = [];
  const query = { update(value) { calls.push(value); return this; }, eq(key, value) { calls.push([key, value]); return this; }, select() { return this; }, async maybeSingle() { return { data: { user_id: 'owner' } }; }, async single() { return { data: { id: 'event' }, error: failure }; } };
  const service = loader({ './organiserSupabase': { organiserSupabase: { auth: { getSession: async () => ({ data: { session } }) }, from: () => query } } })('src/lib/organiser.ts');
  await service.setOrganiserRegistrationsPaused('event', true);
  assert.ok(calls.some(call => !Array.isArray(call) && call.registrations_paused === true));
  for (const filter of [['id', 'event'], ['created_by', 'owner'], ['status', 'active']]) assert.ok(calls.some(call => JSON.stringify(call) === JSON.stringify(filter)));
  calls.length = 0;
  await service.setOrganiserRegistrationsPaused('event', false);
  assert.ok(calls.some(call => !Array.isArray(call) && call.registrations_paused === false));
  failure = { message: 'Refused' };
  await assert.rejects(service.setOrganiserRegistrationsPaused('event', true), e => e === failure);
  session = null;
  await assert.rejects(service.setOrganiserRegistrationsPaused('event', true), /Sign in/);
});

test('PostgreSQL pauses new registrations while allowing rejoining and gameplay, then resumes joining', async t => {
  const db = new PGlite(); t.after(() => db.close());
  await db.exec(`create role anon; create role authenticated; create role service_role bypassrls;
    create schema auth; create table auth.users(id uuid primary key);
    create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
    grant usage on schema auth,public to anon,authenticated,service_role;
    grant execute on function auth.uid() to anon,authenticated,service_role;
    create publication supabase_realtime;`);
  const dir = path.resolve(__dirname, '../supabase/migrations');
  for (const file of fs.readdirSync(dir).sort()) await db.exec(fs.readFileSync(path.join(dir, file), 'utf8').replace('create extension if not exists pgcrypto;', ''));
  const owner = randomUUID(), player = randomUUID(), newcomer = randomUUID(), legacy = randomUUID(), outsider = randomUUID(), event = randomUUID();
  for (const user of [owner, player, newcomer, legacy, outsider]) await db.query('insert into auth.users(id) values($1)', [user]);
  await db.query("insert into organizer_profiles(user_id,display_name) values($1,'Owner')", [owner]);
  await db.query("insert into events(id,slug,name,status,created_by) values($1,'pause-test','Pause test','active',$2)", [event, owner]);
  await db.query("insert into runs(event_id,user_id,display_name) values($1,$2,'Existing crew')", [event, player]);
  await db.query('insert into runs(event_id,user_id) values($1,$2)', [event, legacy]);
  const asUser = async id => { await db.exec('reset role'); await db.query("select set_config('request.jwt.claim.sub',$1,false)", [id]); await db.exec('set role authenticated'); };
  await asUser(owner);
  await db.query('update events set registrations_paused=true where id=$1', [event]);
  assert.equal((await db.query('select status from events where id=$1', [event])).rows[0].status, 'active');
  await asUser(newcomer);
  await assert.rejects(db.query("insert into runs(event_id,user_id,display_name) values($1,$2,'New crew')", [event, newcomer]), /Registrations are paused/);
  await asUser(legacy);
  await assert.rejects(db.query("update runs set display_name='Late crew' where event_id=$1 and user_id=$2", [event, legacy]), /Registrations are paused/);
  await asUser(player);
  await db.query("insert into runs(event_id,user_id,display_name) values($1,$2,'Existing crew') on conflict(event_id,user_id) do update set display_name=excluded.display_name", [event, player]);
  await db.exec('reset role');
  await db.query('update runs set visit_count=1 where event_id=$1 and user_id=$2', [event, player]);
  assert.equal((await db.query('select visit_count from runs where event_id=$1 and user_id=$2', [event, player])).rows[0].visit_count, 1);
  await asUser(outsider);
  assert.equal((await db.query('update events set registrations_paused=false where id=$1 returning id', [event])).rows.length, 0);
  await asUser(owner);
  await db.query('update events set registrations_paused=false where id=$1', [event]);
  await asUser(newcomer);
  await db.query("insert into runs(event_id,user_id,display_name) values($1,$2,'New crew')", [event, newcomer]);
});
