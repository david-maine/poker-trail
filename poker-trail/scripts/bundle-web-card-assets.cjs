const fs = require('node:fs');
const path = require('node:path');

function bundleWebCardAssets() {
  const directory = path.resolve(__dirname, '../assets/images/cards/display');
  const files = fs.readdirSync(directory).filter(name => name.endsWith('.png') && name !== 'card-back-alternate.png').sort();
  const entries = files.filter(name => name !== 'card-back.png').map(name =>
    `  ${JSON.stringify(name.slice(0, -4))}: { uri: ${JSON.stringify('data:image/png;base64,' + fs.readFileSync(path.join(directory, name)).toString('base64'))} },`);
  const back = 'data:image/png;base64,' + fs.readFileSync(path.join(directory, 'card-back.png')).toString('base64');
  fs.writeFileSync(path.resolve(__dirname, '../src/lib/cardImages.web.ts'),
    '// Generated by npm run optimize:cards. Card faces are available offline once the app loads.\n' +
    'import type { ImageSourcePropType } from "react-native";\n\n' +
    'export const CARD_IMAGES: Record<string, ImageSourcePropType> = {\n' + entries.join('\n') + '\n};\n' +
    `export const CARD_BACK_IMAGE: ImageSourcePropType = { uri: ${JSON.stringify(back)} };\n`);
}
module.exports = { bundleWebCardAssets };
if (require.main === module) bundleWebCardAssets();
